#!/usr/bin/env bash
# Seed a load-test user and write scripts/loadtest/.env.loadtest for k6.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/scripts/loadtest/.env.loadtest"
API="${API:-http://127.0.0.1:8080}"
EMAIL="${LOADTEST_EMAIL:-loadtest@local.test}"
PASS="${LOADTEST_PASSWORD:-loadtest-password-12chars}"
NAME="${LOADTEST_NAME:-Load Test User}"

json_get() {
  python3 -c '
import sys, json
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)
v = d
for p in sys.argv[1].split("."):
    if isinstance(v, dict) and p in v:
        v = v[p]
    else:
        sys.exit(0)
if v is not None:
    print(v)
' "$1" 2>/dev/null
}

if ! curl -sf "$API/healthz" >/dev/null; then
  echo "API not reachable at $API" >&2
  echo "  make up && make migrate && make run-api   (deps in Compose; API on host :8080)" >&2
  exit 1
fi

register() {
  curl -sS -X POST "$API/v1/auth/register" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"$EMAIL\",\"password\":\"$PASS\",\"name\":\"$NAME\"}"
}

login() {
  curl -sS -X POST "$API/v1/auth/login" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"$EMAIL\",\"password\":\"$PASS\"}"
}

BODY=$(register)
CODE=$(printf '%s' "$BODY" | json_get tokens.access_token)
if [[ -z "$CODE" ]]; then
  BODY=$(login)
fi
ACCESS=$(printf '%s' "$BODY" | json_get tokens.access_token)
if [[ -z "$ACCESS" ]]; then
  echo "Failed to register/login load-test user at $API" >&2
  printf '%s\n' "$BODY" >&2
  exit 1
fi

BODY=$(curl -sS -X POST "$API/v1/projects" \
  -H "Authorization: Bearer $ACCESS" \
  -H 'Content-Type: application/json' \
  -d '{"name":"Loadtest Project"}')
PID=$(printf '%s' "$BODY" | json_get project.id)
if [[ -z "$PID" ]]; then
  BODY=$(curl -sS "$API/v1/projects" -H "Authorization: Bearer $ACCESS")
  PID=$(printf '%s' "$BODY" | python3 -c '
import sys, json
d = json.load(sys.stdin)
items = d.get("projects") or []
print(items[0]["id"] if items else "")
' 2>/dev/null || true)
fi

cat >"$OUT" <<EOF
# Generated by scripts/loadtest/bootstrap-env.sh — do not commit
API_BASE=$API
ACCESS_TOKEN=$ACCESS
PROJECT_ID=$PID
LOADTEST_EMAIL=$EMAIL
EOF

echo "Wrote $OUT (project_id=${PID:-none})"
